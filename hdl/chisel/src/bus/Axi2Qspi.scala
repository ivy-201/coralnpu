package bus

import chisel3._
import chisel3.util._
import coralnpu.Parameters

object Axi2QspiSerialPhase extends ChiselEnum {
  val Idle, TxRequest, TxLastHold, Turnaround, RxToken, RxStatus, RxReadData,
      Finish = Value
}

object Axi2QspiTransactionPhase extends ChiselEnum {
  val Idle, ReadStart, ReadWait, ReadResponse, WriteData, WriteStart,
      WriteWait, WriteResponse = Value
}

/** AXI subordinate to QSPI controller bridge.
  *
  * Every AXI beat is serialized as one QSPI micro-operation. AXI burst state,
  * IDs, and response aggregation remain local to this bridge. The QSPI clock
  * is generated by dividing the AXI clock; all bridge logic remains in the
  * AXI clock domain and uses clock-enable pulses for QSPI edges.
  */
class Axi2QspiCore(
    p: Parameters,
    sckHalfPeriodCycles: Int,
    responseTimeoutCycles: Int,
    startupSckCycles: Int
) extends Module {
  require(p.axi2AddrBits == QspiAxiProtocol.AddrBits)
  require(p.axi2DataBits == QspiAxiProtocol.DataBits)
  require(p.axi2IdBits >= 1)
  require(sckHalfPeriodCycles >= 1)
  require(responseTimeoutCycles >= 1)
  require(startupSckCycles >= 2)

  val io = IO(new Bundle {
    val axi = Flipped(new AxiMasterIO(
      p.axi2AddrBits, p.axi2DataBits, p.axi2IdBits))
    val qspi = new QspiControllerIO
  })

  val arQueue = Module(new Queue(
    new AxiAddress(p.axi2AddrBits, p.axi2DataBits, p.axi2IdBits), 2))
  val awQueue = Module(new Queue(
    new AxiAddress(p.axi2AddrBits, p.axi2DataBits, p.axi2IdBits), 2))
  val wQueue = Module(new Queue(
    new AxiWriteData(p.axi2DataBits, p.axi2IdBits), 3))
  arQueue.io.enq <> io.axi.read.addr
  awQueue.io.enq <> io.axi.write.addr
  wQueue.io.enq <> io.axi.write.data

  val rValid = RegInit(false.B)
  val rBits = RegInit(0.U.asTypeOf(
    new AxiReadData(p.axi2DataBits, p.axi2IdBits)))
  io.axi.read.data.valid := rValid
  io.axi.read.data.bits := rBits

  val bValid = RegInit(false.B)
  val bBits = RegInit(0.U.asTypeOf(new AxiWriteResponse(p.axi2IdBits)))
  io.axi.write.resp.valid := bValid
  io.axi.write.resp.bits := bBits

  val serialPhase = RegInit(Axi2QspiSerialPhase.Idle)
  val serialWrite = RegInit(false.B)
  val serialAddr = RegInit(0.U(32.W))
  val serialSize = RegInit(0.U(3.W))
  val serialStrb = RegInit(0.U(16.W))
  val serialWriteData = RegInit(0.U(128.W))
  val serialStatus = RegInit(QspiAxiProtocol.StatusOkay.U(8.W))
  val serialReadData = RegInit(0.U(128.W))
  val serialDone = WireDefault(false.B)

  val sckCounterWidth = math.max(1, log2Ceil(sckHalfPeriodCycles))
  val sckCounter = RegInit(0.U(sckCounterWidth.W))
  val sck = RegInit(false.B)
  val csN = RegInit(true.B)
  val dqOe = RegInit(false.B)
  val dqO = RegInit(0.U(4.W))
  val startupCountWidth = math.max(1, log2Ceil(startupSckCycles + 1))
  val startupCount = RegInit(0.U(startupCountWidth.W))
  val startupActive = startupCount =/= startupSckCycles.U

  val serialActive = serialPhase =/= Axi2QspiSerialPhase.Idle
  val clockActive = startupActive || serialActive
  val halfPeriodDone = clockActive && sckCounter === (sckHalfPeriodCycles - 1).U
  val sckRise = halfPeriodDone && !sck
  val sckFall = halfPeriodDone && sck

  when(!clockActive) {
    sckCounter := 0.U
    sck := false.B
  }.elsewhen(halfPeriodDone) {
    sckCounter := 0.U
    sck := !sck
    when(startupActive && sck) {
      startupCount := startupCount + 1.U
    }
  }.otherwise {
    sckCounter := sckCounter + 1.U
  }

  io.qspi.sck := sck.asClock
  io.qspi.csN := csN
  io.qspi.dqO := dqO
  io.qspi.dqOe := dqOe && !csN

  val timeoutWidth = math.max(1, log2Ceil(responseTimeoutCycles + 1))
  val timeoutCounter = RegInit(0.U(timeoutWidth.W))
  val timeoutExpired = timeoutCounter === (responseTimeoutCycles - 1).U
  when(serialPhase === Axi2QspiSerialPhase.RxToken) {
    when(!timeoutExpired) { timeoutCounter := timeoutCounter + 1.U }
  }.otherwise {
    timeoutCounter := 0.U
  }

  val txNibbleIndex = RegInit(0.U(6.W))
  val txLastIndex = Mux(serialWrite, 47.U, 11.U)
  val rxHaveHigh = RegInit(false.B)
  val rxHighNibble = RegInit(0.U(4.W))
  val rxDataIndex = RegInit(0.U(5.W))
  val rxByte = Cat(rxHighNibble, io.qspi.dqI)

  def requestByte(nibbleIndex: UInt): UInt = {
    val byteIndex = nibbleIndex >> 1
    val opcodeByte = Mux(serialWrite,
      QspiAxiProtocol.WriteOpcode.U(8.W), QspiAxiProtocol.ReadOpcode.U(8.W))
    val controlByte = Cat(0.U(5.W), serialSize)
    val addressByteIndex = byteIndex - 2.U
    val addressShift = (3.U - addressByteIndex) << 3
    val addressByte = (serialAddr >> addressShift)(7, 0)
    val strbByteIndex = byteIndex - 6.U
    val strbByte = Mux(strbByteIndex === 0.U,
      serialStrb(15, 8), serialStrb(7, 0))
    val dataByteIndex = byteIndex - 8.U
    val dataByte = (serialWriteData >> (dataByteIndex << 3))(7, 0)

    MuxCase(opcodeByte, Seq(
      (byteIndex === 0.U) -> opcodeByte,
      (byteIndex === 1.U) -> controlByte,
      (byteIndex >= 2.U && byteIndex <= 5.U) -> addressByte,
      (serialWrite && byteIndex >= 6.U && byteIndex <= 7.U) -> strbByte,
      (serialWrite && byteIndex >= 8.U) -> dataByte
    ))
  }

  val txByte = requestByte(txNibbleIndex)
  val currentTxNibble = Mux(txNibbleIndex(0), txByte(3, 0), txByte(7, 4))

  val serialStart = WireDefault(false.B)
  val startWrite = WireDefault(false.B)
  val startAddr = WireDefault(0.U(32.W))
  val startSize = WireDefault(0.U(3.W))
  val startStrb = WireDefault(0.U(16.W))
  val startData = WireDefault(0.U(128.W))

  when(serialStart && serialPhase === Axi2QspiSerialPhase.Idle) {
    serialWrite := startWrite
    serialAddr := startAddr
    serialSize := startSize
    serialStrb := startStrb
    serialWriteData := startData
    serialStatus := QspiAxiProtocol.StatusOkay.U
    serialReadData := 0.U
    txNibbleIndex := 0.U
    rxHaveHigh := false.B
    rxDataIndex := 0.U
    timeoutCounter := 0.U
    csN := false.B
    dqOe := true.B
    dqO := Mux(startWrite,
      (QspiAxiProtocol.WriteOpcode >> 4).U,
      (QspiAxiProtocol.ReadOpcode >> 4).U)
    serialPhase := Axi2QspiSerialPhase.TxRequest
  }

  when(serialPhase === Axi2QspiSerialPhase.TxRequest && sckFall) {
    val nextNibbleIndex = txNibbleIndex + 1.U
    val nextTxByte = requestByte(nextNibbleIndex)
    txNibbleIndex := nextNibbleIndex
    dqO := Mux(nextNibbleIndex(0), nextTxByte(3, 0), nextTxByte(7, 4))
  }

  when(serialPhase === Axi2QspiSerialPhase.TxRequest && sckRise &&
       txNibbleIndex === txLastIndex) {
    serialPhase := Axi2QspiSerialPhase.TxLastHold
  }

  when(serialPhase === Axi2QspiSerialPhase.TxLastHold && sckFall) {
    dqOe := false.B
    rxHaveHigh := false.B
    serialPhase := Axi2QspiSerialPhase.Turnaround
  }

  // The target consumes this rising edge as the one-cycle turnaround and starts
  // driving on the following falling edge.
  when(serialPhase === Axi2QspiSerialPhase.Turnaround && sckRise) {
    serialPhase := Axi2QspiSerialPhase.RxToken
  }

  def receiveByte(body: UInt => Unit): Unit = {
    when(sckRise) {
      when(!rxHaveHigh) {
        rxHighNibble := io.qspi.dqI
        rxHaveHigh := true.B
      }.otherwise {
        rxHaveHigh := false.B
        body(rxByte)
      }
    }
  }

  when(serialPhase === Axi2QspiSerialPhase.RxToken) {
    receiveByte { byte =>
      when(byte === QspiAxiProtocol.ReadyToken.U) {
        serialPhase := Axi2QspiSerialPhase.RxStatus
      }.elsewhen(byte =/= QspiAxiProtocol.BusyToken.U) {
        serialStatus := QspiAxiProtocol.StatusFramingError.U
        serialPhase := Axi2QspiSerialPhase.Finish
      }
    }
  }

  when(serialPhase === Axi2QspiSerialPhase.RxStatus) {
    receiveByte { byte =>
      serialStatus := byte
      when(!serialWrite && QspiAxiProtocol.isSuccessfulStatus(byte)) {
        rxDataIndex := 0.U
        serialPhase := Axi2QspiSerialPhase.RxReadData
      }.otherwise {
        serialPhase := Axi2QspiSerialPhase.Finish
      }
    }
  }

  when(serialPhase === Axi2QspiSerialPhase.RxReadData) {
    receiveByte { byte =>
      serialReadData := serialReadData | (byte << (rxDataIndex << 3))
      when(rxDataIndex === 15.U) {
        serialPhase := Axi2QspiSerialPhase.Finish
      }.otherwise {
        rxDataIndex := rxDataIndex + 1.U
      }
    }
  }

  when(serialPhase === Axi2QspiSerialPhase.RxToken && timeoutExpired) {
    serialStatus := QspiAxiProtocol.StatusTimeout.U
    serialPhase := Axi2QspiSerialPhase.Finish
  }

  when(serialPhase === Axi2QspiSerialPhase.Finish) {
    dqOe := false.B
    when(!sck || sckFall) {
      csN := true.B
      sck := false.B
      sckCounter := 0.U
      serialPhase := Axi2QspiSerialPhase.Idle
      serialDone := true.B
    }
  }

  val transactionPhase = RegInit(Axi2QspiTransactionPhase.Idle)
  val transactionAddr = RegInit(0.U(32.W))
  val transactionId = RegInit(0.U(p.axi2IdBits.W))
  val transactionLen = RegInit(0.U(8.W))
  val transactionSize = RegInit(0.U(3.W))
  val transactionBurst = RegInit(AxiBurstType.INCR.asUInt)
  val transactionWrapBase = RegInit(0.U(32.W))
  val transactionInvalid = RegInit(false.B)
  val beatIndex = RegInit(0.U(8.W))
  val accumulatedWriteResp = RegInit(AxiResponseType.OKAY.asUInt)
  val writeBeatData = RegInit(0.U(128.W))
  val writeBeatStrb = RegInit(0.U(16.W))
  val writeBeatLast = RegInit(false.B)
  val preferWrite = RegInit(false.B)

  arQueue.io.deq.ready := false.B
  awQueue.io.deq.ready := false.B
  wQueue.io.deq.ready := false.B

  def burstSupported(burst: UInt): Bool =
    burst === AxiBurstType.FIXED.asUInt ||
      burst === AxiBurstType.INCR.asUInt ||
      burst === AxiBurstType.WRAP.asUInt

  def transferBase(addr: UInt, size: UInt): UInt =
    ((addr >> size) << size)(31, 0)

  def nextAddress(
      addr: UInt, size: UInt, burst: UInt, wrapBase: UInt): UInt = {
    val incremented = addr + (1.U << size)
    MuxLookup(burst, incremented)(Seq(
      AxiBurstType.FIXED.asUInt -> addr,
      AxiBurstType.INCR.asUInt -> incremented,
      AxiBurstType.WRAP.asUInt -> Mux(
        incremented >= wrapBase + 16.U, wrapBase, incremented)
    ))
  }

  def mapStatus(status: UInt): UInt =
    Mux(QspiAxiProtocol.isAxiStatus(status), status(1, 0),
      AxiResponseType.SLVERR.asUInt)

  val chooseWrite = awQueue.io.deq.valid &&
    (!arQueue.io.deq.valid || preferWrite)

  when(transactionPhase === Axi2QspiTransactionPhase.Idle &&
       !startupActive && !rValid && !bValid) {
    when(chooseWrite) {
      awQueue.io.deq.ready := true.B
      when(awQueue.io.deq.fire) {
        transactionAddr := awQueue.io.deq.bits.addr
        transactionWrapBase := transferBase(
          awQueue.io.deq.bits.addr, awQueue.io.deq.bits.size)
        transactionId := awQueue.io.deq.bits.id
        transactionLen := awQueue.io.deq.bits.len
        transactionSize := awQueue.io.deq.bits.size
        transactionBurst := awQueue.io.deq.bits.burst
        transactionInvalid := awQueue.io.deq.bits.size > QspiAxiProtocol.MaxSize.U ||
          !burstSupported(awQueue.io.deq.bits.burst)
        beatIndex := 0.U
        accumulatedWriteResp := Mux(
          awQueue.io.deq.bits.size > QspiAxiProtocol.MaxSize.U ||
            !burstSupported(awQueue.io.deq.bits.burst),
          AxiResponseType.SLVERR.asUInt,
          AxiResponseType.OKAY.asUInt)
        transactionPhase := Axi2QspiTransactionPhase.WriteData
        preferWrite := false.B
      }
    }.elsewhen(arQueue.io.deq.valid) {
      arQueue.io.deq.ready := true.B
      when(arQueue.io.deq.fire) {
        transactionAddr := arQueue.io.deq.bits.addr
        transactionWrapBase := transferBase(
          arQueue.io.deq.bits.addr, arQueue.io.deq.bits.size)
        transactionId := arQueue.io.deq.bits.id
        transactionLen := arQueue.io.deq.bits.len
        transactionSize := arQueue.io.deq.bits.size
        transactionBurst := arQueue.io.deq.bits.burst
        transactionInvalid := arQueue.io.deq.bits.size > QspiAxiProtocol.MaxSize.U ||
          !burstSupported(arQueue.io.deq.bits.burst)
        beatIndex := 0.U
        preferWrite := true.B
        when(arQueue.io.deq.bits.size > QspiAxiProtocol.MaxSize.U ||
             !burstSupported(arQueue.io.deq.bits.burst)) {
          rBits.id := arQueue.io.deq.bits.id
          rBits.data := 0.U
          rBits.resp := AxiResponseType.SLVERR.asUInt
          rBits.last := arQueue.io.deq.bits.len === 0.U
          rValid := true.B
          transactionPhase := Axi2QspiTransactionPhase.ReadResponse
        }.otherwise {
          transactionPhase := Axi2QspiTransactionPhase.ReadStart
        }
      }
    }
  }

  when(transactionPhase === Axi2QspiTransactionPhase.ReadStart &&
       serialPhase === Axi2QspiSerialPhase.Idle) {
    when(transactionInvalid) {
      rBits.id := transactionId
      rBits.data := 0.U
      rBits.resp := AxiResponseType.SLVERR.asUInt
      rBits.last := beatIndex === transactionLen
      rValid := true.B
      transactionPhase := Axi2QspiTransactionPhase.ReadResponse
    }.otherwise {
      serialStart := true.B
      startWrite := false.B
      startAddr := transactionAddr
      startSize := transactionSize
      transactionPhase := Axi2QspiTransactionPhase.ReadWait
    }
  }

  when(transactionPhase === Axi2QspiTransactionPhase.ReadWait && serialDone) {
    rBits.id := transactionId
    rBits.data := serialReadData
    rBits.resp := mapStatus(serialStatus)
    rBits.last := beatIndex === transactionLen
    rValid := true.B
    transactionPhase := Axi2QspiTransactionPhase.ReadResponse
  }

  when(transactionPhase === Axi2QspiTransactionPhase.ReadResponse &&
       io.axi.read.data.fire) {
    rValid := false.B
    when(rBits.last) {
      transactionPhase := Axi2QspiTransactionPhase.Idle
    }.otherwise {
      transactionAddr := nextAddress(
        transactionAddr, transactionSize, transactionBurst, transactionWrapBase)
      beatIndex := beatIndex + 1.U
      transactionPhase := Axi2QspiTransactionPhase.ReadStart
    }
  }

  when(transactionPhase === Axi2QspiTransactionPhase.WriteData) {
    wQueue.io.deq.ready := true.B
    when(wQueue.io.deq.fire) {
      val expectedLast = beatIndex === transactionLen
      val invalidBeat = transactionInvalid

      writeBeatData := wQueue.io.deq.bits.data
      writeBeatStrb := wQueue.io.deq.bits.strb
      writeBeatLast := wQueue.io.deq.bits.last

      assert(wQueue.io.deq.bits.last === expectedLast)

      when(invalidBeat) {
        accumulatedWriteResp := AxiResponseType.SLVERR.asUInt
        when(expectedLast || wQueue.io.deq.bits.last) {
          bBits.id := transactionId
          bBits.resp := AxiResponseType.SLVERR.asUInt
          bValid := true.B
          transactionPhase := Axi2QspiTransactionPhase.WriteResponse
        }.otherwise {
          transactionAddr := nextAddress(
            transactionAddr, transactionSize, transactionBurst, transactionWrapBase)
          beatIndex := beatIndex + 1.U
        }
      }.elsewhen(wQueue.io.deq.bits.last && !expectedLast) {
        accumulatedWriteResp := AxiResponseType.SLVERR.asUInt
        bBits.id := transactionId
        bBits.resp := AxiResponseType.SLVERR.asUInt
        bValid := true.B
        transactionPhase := Axi2QspiTransactionPhase.WriteResponse
      }.otherwise {
        transactionPhase := Axi2QspiTransactionPhase.WriteStart
      }
    }
  }

  when(transactionPhase === Axi2QspiTransactionPhase.WriteStart &&
       serialPhase === Axi2QspiSerialPhase.Idle) {
    serialStart := true.B
    startWrite := true.B
    startAddr := transactionAddr
    startSize := transactionSize
    startStrb := writeBeatStrb
    startData := writeBeatData
    transactionPhase := Axi2QspiTransactionPhase.WriteWait
  }

  when(transactionPhase === Axi2QspiTransactionPhase.WriteWait && serialDone) {
    val beatResp = mapStatus(serialStatus)
    val expectedLast = beatIndex === transactionLen
    val lastMismatch = writeBeatLast =/= expectedLast
    val currentResp = Mux(
      lastMismatch, AxiResponseType.SLVERR.asUInt, beatResp)
    val finalResp = Mux(
      accumulatedWriteResp(1), accumulatedWriteResp,
      Mux(currentResp(1), currentResp,
        Mux(accumulatedWriteResp === AxiResponseType.EXOKAY.asUInt,
          accumulatedWriteResp, currentResp)))
    accumulatedWriteResp := finalResp

    when(writeBeatLast || expectedLast) {
      bBits.id := transactionId
      bBits.resp := finalResp
      bValid := true.B
      transactionPhase := Axi2QspiTransactionPhase.WriteResponse
    }.otherwise {
      transactionAddr := nextAddress(
        transactionAddr, transactionSize, transactionBurst, transactionWrapBase)
      beatIndex := beatIndex + 1.U
      transactionPhase := Axi2QspiTransactionPhase.WriteData
    }
  }

  when(transactionPhase === Axi2QspiTransactionPhase.WriteResponse &&
       io.axi.write.resp.fire) {
    bValid := false.B
    transactionPhase := Axi2QspiTransactionPhase.Idle
  }

  assert(!io.qspi.csN || !io.qspi.dqOe)
  assert(io.qspi.csN || serialActive)
  when(startupActive) {
    assert(io.qspi.csN)
    assert(!io.qspi.dqOe)
  }

  val previousReadData = RegNext(io.axi.read.data.bits)
  val previousWriteResp = RegNext(io.axi.write.resp.bits)
  val readWasStalled = RegNext(
    io.axi.read.data.valid && !io.axi.read.data.ready, false.B)
  val writeRespWasStalled = RegNext(
    io.axi.write.resp.valid && !io.axi.write.resp.ready, false.B)
  when(readWasStalled) {
    assert(io.axi.read.data.valid)
    assert(io.axi.read.data.bits.asUInt === previousReadData.asUInt)
  }
  when(writeRespWasStalled) {
    assert(io.axi.write.resp.valid)
    assert(io.axi.write.resp.bits.asUInt === previousWriteResp.asUInt)
  }
}

/** Raw top-level with CoreAxi-compatible clock and reset naming. */
class Axi2Qspi(
    p: Parameters,
    sckHalfPeriodCycles: Int = 4,
    responseTimeoutCycles: Int = 65536,
    startupSckCycles: Int = 2
) extends RawModule {
  val io = IO(new Bundle {
    val aclk = Input(Clock())
    val aresetn = Input(AsyncReset())
    val axi = Flipped(new AxiMasterIO(
      p.axi2AddrBits, p.axi2DataBits, p.axi2IdBits))
    val qspi = new QspiControllerIO
  })

  val resetSync = Module(new QspiResetSynchronizer)
  resetSync.io.clock := io.aclk
  resetSync.io.asyncAssert := !io.aresetn.asBool

  val core = withClockAndReset(io.aclk, resetSync.io.resetOut.asAsyncReset) {
    Module(new Axi2QspiCore(
      p, sckHalfPeriodCycles, responseTimeoutCycles, startupSckCycles))
  }
  core.io.axi <> io.axi
  io.qspi <> core.io.qspi
}

import _root_.circt.stage.{ChiselStage, FirtoolOption}
import chisel3.stage.ChiselGeneratorAnnotation
import scala.annotation.nowarn

@nowarn
object EmitAxi2Qspi extends App {
  val p = Parameters()
  p.lsuDataBits = QspiAxiProtocol.DataBits
  (new ChiselStage).execute(
    Array("--target", "systemverilog") ++ args,
    Seq(ChiselGeneratorAnnotation(() => new Axi2Qspi(p))) ++
      Seq(FirtoolOption("-enable-layers=Verification"))
  )
}
